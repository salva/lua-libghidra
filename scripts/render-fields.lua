-- Render field facts, never runtime acceptance, from the pinned source ledger.
package.path = 'scripts/?.lua;' .. package.path
local json = require('tool_json')
local M = {}
local function cell(v)
  if v == json.null or v == nil then return '—' end
  return tostring(v):gsub('|', '&#124;'):gsub('\n', ' ')
end
local function linked(text)
 for name in text:gmatch('table model ([%w_]+)') do
  text=text:gsub('table model '..name, 'table model ['..name..'](#'..name:lower()..')')
 end
 for name in text:gmatch('enum ([%w_]+):') do
  text=text:gsub('enum '..name..':', 'enum ['..name..'](#'..name:lower()..'):')
 end
 return text
end
-- Presentation only: the ledger remains the sole model/field authority.
local exceptions = {HealthStatus=1, Capability=1, BytePatch=2}
local titles = {'Records and result values', 'Requests options and input items',
 'Response envelopes', 'Supported enums', 'Native-only schemas', 'Native-only enums'}
local function slug(name) return name:lower():gsub(' ', '-') end
function M.partition(ledger)
 local groups, seen = {}, {}
 for i=1,#titles do groups[i]={} end
 local function assign(name, model, enum)
  assert(not seen[name], 'duplicate model '..name)
  seen[name]=true
  local scope=model.lua_scope
  assert(scope=='included' or scope=='native-only', 'unknown scope for '..name)
  local candidates={}
  if scope=='native-only' then candidates[enum and 6 or 5]=true
  elseif enum then candidates[4]=true
  else
   if name:match('Record$') then candidates[1]=true end
   if name:match('Request$') or name:match('Options$') then candidates[2]=true end
   if name:match('Response$') then candidates[3]=true end
   if exceptions[name] then candidates[exceptions[name]]=true end
  end
  local group
  for i in pairs(candidates) do
   assert(not group, 'multiply assigned model '..name); group=i
  end
  assert(group, 'unassigned included model '..name)
  groups[group][#groups[group]+1]=name
 end
 for name,model in pairs(ledger.types) do assign(name,model,false) end
 for name,model in pairs(ledger.enums) do assign(name,model,true) end
 local emitted={}
 for i,names in ipairs(groups) do
  table.sort(names)
  for _,name in ipairs(names) do
   assert(not emitted[name], 'duplicate output '..name); emitted[name]=i
  end
 end
 for name in pairs(ledger.types) do assert(emitted[name], 'missing type '..name) end
 for name in pairs(ledger.enums) do assert(emitted[name], 'missing enum '..name) end
 for name,i in pairs(exceptions) do
  assert(ledger.types[name] and emitted[name]==i, 'wrong exception partition '..name)
 end
 return groups
end
function M.render(ledger)
 local groups=M.partition(ledger)
local out = {'# Native field manifest\n\n',
 'Generated by `lua5.4 scripts/render-fields.lua` from `api/coverage.json`.\n',
 'Source facts only, **not runtime acceptance or Lua call grammar**. See\n',
 '[API](../docs/API.md) for call grammar, validation and effective bounds.\n',
 'Included means reachable from an implemented native operation or the local\n',
 'factory, not a populated producer or independently qualified runtime result.\n',
 'Native-only models/enums have no supported Lua conversion claim. Defaults\n',
 'do not imply optional positional arguments. UInt64 never uses floats.\n\n'}
out[#out+1]='## Index\n\n'
for i,names in ipairs(groups) do
 out[#out+1]='- ['..titles[i]..'](#'..slug(titles[i])..')\n'
 for _,name in ipairs(names) do
  out[#out+1]='  - ['..name..'](#'..name:lower()..')\n'
 end
end
out[#out+1]='\n'
for i,names in ipairs(groups) do
 out[#out+1]='## '..titles[i]..'\n\n'
 for _,name in ipairs(names) do
  if i==4 or i==6 then
   local e=ledger.enums[name]
   out[#out+1]='### '..name..'\n\n'..(e.lua_scope=='included' and require('inventory_source').lua(name,ledger) or 'Native-only enum; no supported Lua conversion claim.')..'\n\nNative values: `'..cell(e.values)..'`. Reachability: '..e.operation_reachability..'.\n\n'
  else
   local t=ledger.types[name]
   out[#out+1]='### '..name..'\n\n'..(t.lua_scope=='included' and 'Included operation/factory schema.' or 'Native-only schema; no supported Lua conversion claim.')..' Reachability: '..t.operation_reachability..'.\n\n| Field | Native type | Lua | Optional | Native default |\n| --- | --- | --- | --- | --- |\n'
   for _,f in ipairs(t.fields) do
    out[#out+1]='| '..cell(f.name)..' | '..cell(f.native_type)..' | '..cell(t.lua_scope=='included' and linked(f.lua) or ('native schema: '..f.native_type..'; no supported Lua conversion'))..' | '..cell(f.optional)..' | '..cell(f.native_default)..' |\n'
   end
   out[#out+1]='\n'
  end
 end
end
return table.concat(out)
end
-- Loading the same renderer for sensitivity tests performs no file I/O.
if ... == 'render-fields' then return M end
assert(#arg==0 or (#arg==1 and arg[1]=='--check'),
 'usage: lua5.4 scripts/render-fields.lua [--check]')
local input=assert(io.open('api/coverage.json','rb'))
local ledger=json.decode(input:read('*a')); input:close()
local text=M.render(ledger)
if arg[1]=='--check' then
 local f=assert(io.open('api/FIELDS.md','rb'))
 assert(f:read('*a')==text,'api/FIELDS.md is stale'); f:close()
else
 local f=assert(io.open('api/FIELDS.md','wb')); assert(f:write(text)); f:close()
end
